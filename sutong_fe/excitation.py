"""
Ambient excitation of the simulated monitoring records.

One record is driven by exactly one seeded random draw of the two
operational load sources of the bridge:

* **wind** - quasi-steady turbulent wind at deck level: longitudinal
  turbulence (drag on the girder and on both pylons) and vertical
  turbulence (lift on the girder), generated by spectral representation on
  a master time grid with Kaimal- and Panofsky-type spectral shapes and an
  exponential spanwise coherence (Davenport decay).  Each spectrum is
  scaled to its exact target variance;
* **traffic** - a Poisson stream of cars and three-axle trucks crossing
  the cable-stayed unit in both directions at random speeds, each axle
  applied as a moving point load on the girder mesh.

Every record - also records of the *same* scenario - draws a fresh wind
field, a fresh traffic fleet and fresh sensor noise, so no two records in
the dataset share an excitation realisation.  The only systematic
difference between scenarios is the damage state of the structure.

All amplitudes live in ``params.EXCITATION``; nothing is hard-coded here.
"""

import numpy as np
import scipy.sparse as sp

from . import params as P


# ---------------------------------------------------------------------------
# wind field
# ---------------------------------------------------------------------------
def _kaimal_shape(f, tau):
    """Kaimal-type spectral shape of the longitudinal turbulence."""
    return 200.0 / (1.0 + 50.0 * f * tau) ** (5.0 / 3.0)


def _panofsky_shape(f, tau):
    """Panofsky-type spectral shape of the vertical turbulence."""
    return 1.0 / (1.0 + 4.0 * f * tau) ** 2.0


class WindField:
    """Seeded turbulent wind field on a coarse spatial grid.

    The field lives on ``wind_points`` positions along the unit.  It is
    generated once on the master time grid (``T_total`` at ``fs``) by
    spectral representation with random phases, band-limited to the wind
    band, and later evaluated by linear interpolation.
    """

    def __init__(self, rng, T_total, fs):
        cfg = P.EXCITATION
        U = cfg["wind_U"]
        n_pts = cfg["wind_points"]
        self.xg = np.linspace(0.0, P.TOTAL_LENGTH, n_pts)
        self.fs = fs
        self.n_t = int(round(T_total * fs))
        self.U = U

        # target standard deviations and time scales of the two components
        sigma_u = cfg["I_u"] * U
        sigma_w = cfg["I_w"] * U
        tau_u = 70.0 / U             # integral time scale at deck level
        tau_w = 0.4 * tau_u

        f = np.fft.rfftfreq(self.n_t, d=1.0 / fs)
        df = f[1]
        band = (f >= df) & (f <= cfg["wind_f_max"])    # no DC component
        S_u = _kaimal_shape(f, tau_u) * band
        S_w = _panofsky_shape(f, tau_w) * band
        # scale each spectrum to its exact target variance
        S_u *= sigma_u ** 2 / max(S_u.sum() * df, 1e-30)
        S_w *= sigma_w ** 2 / max(S_w.sum() * df, 1e-30)

        c = cfg["coherence_c"]
        dx = np.abs(self.xg[:, None] - self.xg[None, :])
        self.u = self._realise(rng, S_u, f, dx, c, U)
        self.w = self._realise(rng, S_w, f, dx, c, U)

    def _realise(self, rng, S, f, dx, c, U):
        """Spectral representation of one component with coherence.

        At every frequency bin the cross-spectral matrix is
        ``S(f) * exp(-c f |dx| / U)``; its Cholesky factor colours a vector
        of independent unit-variance complex Gaussians, and the inverse
        real FFT assembles the band-limited time series on the spatial
        grid.  The amplitude scaling makes the drawn variance match
        ``sum(S) * df`` exactly.
        """
        X = np.zeros((len(self.xg), self.n_t), dtype=complex)
        n = self.n_t
        df = f[1] - f[0]
        for k in range(1, len(f)):
            if S[k] <= 0.0:
                continue
            coh = np.exp(-c * f[k] * dx / U)
            Lm = np.linalg.cholesky(coh)
            z = (rng.standard_normal(len(self.xg)) +
                 1j * rng.standard_normal(len(self.xg))) / np.sqrt(2.0)
            # irfft variance law: Var(x) = 2 sum_k E|X_k|^2 / n^2, and the
            # spectrum is normalised to sum(S) * df, hence
            amp = np.sqrt(S[k] * df * n * n / 2.0)
            X[:, k] = Lm @ (amp * z)
        return np.fft.irfft(X, n=n, axis=1)


# ---------------------------------------------------------------------------
# traffic stream
# ---------------------------------------------------------------------------
class TrafficStream:
    """Seeded Poisson stream of vehicles crossing the unit.

    Each vehicle has a gross weight drawn from the truck / car populations,
    a random speed and direction, and its axle loads travel as moving point
    forces on the girder.  The stream starts before the record window so
    that vehicles are already on the bridge when the record begins.
    """

    def __init__(self, rng, T_total):
        cfg = P.EXCITATION
        v_min = cfg["car_speed"][0] - 3.0 * cfg["car_speed"][1]
        pre_history = P.TOTAL_LENGTH / max(v_min, 5.0) + 20.0
        rate = cfg["traffic_rate"]

        self.axles = []
        t = -pre_history
        while True:
            t += rng.exponential(1.0 / rate)
            if t > T_total:
                break
            truck = rng.random() < cfg["truck_fraction"]
            if truck:
                g = np.inf
                while g < 2.0e5 or g > 1.0e6:
                    g = rng.normal(*cfg["truck_gauss"])
                fracs = cfg["truck_axle_fractions"]
                v = max(rng.normal(*cfg["truck_speed"]), 12.0)
                offs = (0.0, rng.uniform(3.4, 4.2), rng.uniform(9.0, 11.0))
            else:
                g = min(max(rng.normal(*cfg["car_gauss"]), 1.0e4), 1.0e5)
                fracs = cfg["car_axle_fractions"]
                v = max(rng.normal(*cfg["car_speed"]), 15.0)
                offs = (0.0, rng.uniform(2.6, 3.4))
            direction = 1.0 if rng.random() < 0.5 else -1.0
            for off, fr in zip(offs, fracs):
                self.axles.append(dict(
                    t_entry=t + off / v, v=v, direction=direction,
                    force=g * fr))

    def vertical_forces(self, deck_xs, t):
        """Moving axle loads accumulated on the deck nodes.

        Returns ``F[n_nodes, n_t]`` of downward nodal forces (N).
        """
        F = np.zeros((len(deck_xs), len(t)))
        n_t = len(t)
        flat = F.reshape(-1)
        dt_mesh = deck_xs[1] - deck_xs[0]
        n_max = len(deck_xs) - 1
        for ax in self.axles:
            pos = ax["direction"] * ax["v"] * (t - ax["t_entry"]) + \
                (0.0 if ax["direction"] > 0 else P.TOTAL_LENGTH)
            inside = (pos >= 0.0) & (pos <= P.TOTAL_LENGTH - dt_mesh / 2.0)
            if not inside.any():
                continue
            fi = pos[inside] / dt_mesh
            i0 = np.clip(np.floor(fi).astype(int), 0, n_max - 1)
            r = np.clip(fi - i0, 0.0, 1.0)
            cols = np.flatnonzero(inside)
            np.add.at(flat, i0 * n_t + cols, ax["force"] * (1.0 - r))
            np.add.at(flat, (i0 + 1) * n_t + cols, ax["force"] * r)
        return F


# ---------------------------------------------------------------------------
# combined record excitation on the structural nodes
# ---------------------------------------------------------------------------
def _interp_rows(xs, xg):
    """Sparse linear-interpolation rows (len(xs) x len(xg))."""
    rows, cols, vals = [], [], []
    dx = xg[1] - xg[0]
    for i, x in enumerate(xs):
        fi = np.clip(x / dx, 0.0, len(xg) - 1.000001)
        j = int(np.floor(fi))
        r = fi - j
        rows += [i, i]
        cols += [j, min(j + 1, len(xg) - 1)]
        vals += [1.0 - r, r]
    return sp.coo_matrix((vals, (rows, cols)),
                         shape=(len(xs), len(xg))).tocsr()


class AmbientExcitation:
    """Wind + traffic of one record, evaluated on the structural model.

    ``forces(t)`` returns the external-force matrix over the loaded free
    rows (deck vertical, deck longitudinal, pylon longitudinal), with
    ``t`` taken from the master 200 Hz grid so the wind field can be
    sliced directly.
    """

    def __init__(self, model, rng, T_total, fs_master):
        cfg = P.EXCITATION
        self.model = model
        self.cfg = cfg
        self.fs_master = fs_master
        self.wind = WindField(rng, T_total, fs_master)
        self.traffic = TrafficStream(rng, T_total)

        geo = model.geo
        self.deck_xs = model.deck_xs
        self.deck_w_rows = np.array(
            [model.dof_map[3 * n + 1] for n in model.deck_nids])
        self.deck_u_rows = np.array(
            [model.dof_map[3 * n] for n in model.deck_nids])

        # deck tributary lengths (m) for the wind line loads
        trib = np.full(len(self.deck_xs), P.DECK_MESH)
        trib[0] = trib[-1] = P.DECK_MESH / 2.0
        self.trib = trib

        # pylon nodes above the bases: drag rows with tributary heights
        self.pylon_drag = []
        for p, xp in enumerate(P.PYLON_X):
            ys = sorted(n.y for n in geo.nodes
                        if n.group == "pylon" and n.x == xp and n.y > 1e-9)
            for k, y in enumerate(ys):
                nid = self._pylon_nid(xp, y)
                if k == 0:
                    h = (ys[1] - ys[0]) / 2.0
                elif k == len(ys) - 1:
                    h = (ys[-1] - ys[-2]) / 2.0
                else:
                    h = (ys[k + 1] - ys[k - 1]) / 2.0
                row = _interp_rows([xp], self.wind.xg)
                self.pylon_drag.append(
                    (model.dof_map[3 * nid], h, row))

        # wind interpolation weights from the coarse grid to the deck
        self.iwind = _interp_rows(self.deck_xs, self.wind.xg)

    def _pylon_nid(self, xp, y):
        for n in self.model.geo.nodes:
            if n.group == "pylon" and n.x == xp and abs(n.y - y) < 1e-6:
                return n.nid
        raise ValueError(f"pylon node at y={y} not found")

    # -- loaded-row bookkeeping ------------------------------------------
    def loaded_rows(self):
        return np.concatenate([
            self.deck_w_rows, self.deck_u_rows,
            np.array([r for (r, _, _) in self.pylon_drag])])

    def n_rows(self):
        return 2 * len(self.deck_w_rows) + len(self.pylon_drag)

    # -- force assembly ----------------------------------------------------
    def forces(self, t):
        """External forces on the loaded free rows at master-grid times
        ``t`` (N, rows x len(t))."""
        cfg = self.cfg
        idx = np.rint(np.asarray(t) * self.fs_master).astype(int)
        n_t = len(t)
        nd = len(self.deck_w_rows)

        # wind components at the deck nodes
        u_deck = self.iwind @ self.wind.u[:, idx]
        w_deck = self.iwind @ self.wind.w[:, idx]

        # quasi-steady wind pressures (N/m on the girder)
        q_z = 0.5 * cfg["rho_air"] * cfg["wind_U"] * P.GIRDER["width"] * \
            cfg["CL_prime"] * w_deck
        q_x = cfg["rho_air"] * cfg["Cd_deck"] * P.GIRDER["width"] * \
            cfg["wind_U"] * u_deck
        Fz_wind = q_z * self.trib[:, None]
        Fx_deck = q_x * self.trib[:, None]

        # traffic (downward)
        F_traffic = -self.traffic.vertical_forces(self.deck_xs, t)

        # pylon drag from the longitudinal turbulence at the pylon axes
        Fx_pyl = np.zeros((len(self.pylon_drag), n_t))
        for k, (row, h, interp) in enumerate(self.pylon_drag):
            u_at = interp @ self.wind.u[:, idx]
            Fx_pyl[k] = cfg["rho_air"] * cfg["Cd_pylon"] * \
                cfg["pylon_width"] * cfg["wind_U"] * u_at[0] * h

        F = np.zeros((self.n_rows(), n_t))
        F[:nd] = Fz_wind + F_traffic
        F[nd:2 * nd] = Fx_deck
        F[2 * nd:] = Fx_pyl
        return F
